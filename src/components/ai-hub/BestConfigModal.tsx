import React, { useState, useMemo } from 'react';
import { TopologyAnalysisResult, StationRecommendation } from '../../types/api-sync';
import {
  generateNewApiChannelJson,
  generateBatchNewApiImportJson,
  generateChannelsBatchCurlScript,
} from '../../utils/api-station-sync';
import { copyToClipboard } from '../../utils/clipboard';
import { useModalLock } from '../../utils/use-modal-lock';
import { UiIcon } from '../awesome-ui/UiIcon';

interface BestConfigModalProps {
  isOpen: boolean;
  onClose: () => void;
  analysis: TopologyAnalysisResult;
  apiEndpoint: string;
}

export const BestConfigModal: React.FC<BestConfigModalProps> = ({
  isOpen,
  onClose,
  analysis,
  apiEndpoint,
}) => {
  const [activeTab, setActiveTab] = useState<'topology' | 'batch_json' | 'curl' | 'clients'>('topology');
  const [copiedBatch, setCopiedBatch] = useState(false);
  const [copiedCurl, setCopiedCurl] = useState(false);
  const [copiedSingleId, setCopiedSingleId] = useState<string | null>(null);
  const [apiKeyPlaceholder, setApiKeyPlaceholder] = useState('');

  useModalLock(isOpen, onClose);

  if (!isOpen) return null;

  const keyToUse = apiKeyPlaceholder.trim() || 'sk-your-upstream-token-here';
  const batchPayload = generateBatchNewApiImportJson(analysis.recommendations, keyToUse);
  const batchJsonString = JSON.stringify(batchPayload, null, 2);

  // Multi-channel curl script generated by the shared, injection-safe builder
  const curlScript = useMemo(
    () => generateChannelsBatchCurlScript(analysis.recommendations, apiEndpoint, keyToUse),
    [analysis.recommendations, apiEndpoint, keyToUse]
  );

  const uniqueTierCount = useMemo(
    () => new Set(analysis.recommendations.map((rec) => rec.tier)).size,
    [analysis.recommendations]
  );

  const handleCopyBatch = async () => {
    const success = await copyToClipboard(batchJsonString);
    if (success) {
      setCopiedBatch(true);
      setTimeout(() => setCopiedBatch(false), 2000);
    }
  };

  const handleCopyCurl = async () => {
    const success = await copyToClipboard(curlScript);
    if (success) {
      setCopiedCurl(true);
      setTimeout(() => setCopiedCurl(false), 2000);
    }
  };

  const handleCopySingle = async (rec: StationRecommendation) => {
    const singlePayload = generateNewApiChannelJson(rec.station, rec, keyToUse);
    const success = await copyToClipboard(JSON.stringify(singlePayload, null, 2));
    if (success) {
      setCopiedSingleId(rec.station.id);
      setTimeout(() => setCopiedSingleId(null), 2000);
    }
  };

  return (
    <div className="modal-overlay" onClick={onClose}>
      <div
        className="modal-sheet !max-w-3xl"
        onClick={(e) => e.stopPropagation()}
        role="dialog"
        aria-modal="true"
      >
        {/* Top Header */}
        <div className="topbar">
          <button className="back-btn" onClick={onClose} type="button">
            <UiIcon name="arrow-left" size={14} strokeWidth={2.2} />
            <span>返回公益站列表</span>
          </button>
          <div className="flex items-center gap-1.5 text-xs text-[var(--ink-soft)]">
            <UiIcon name="server" size={13} className="text-emerald-600" />
            <span className="font-mono">{apiEndpoint}</span>
          </div>
        </div>

        {/* Hero Title & Analysis Badge */}
        <div className="card-title flex items-center gap-2">
          <UiIcon name="sparkles" size={20} className="text-amber-500" />
          <span>AI 公益站最佳拓扑配置方案</span>
        </div>
        <p className="mt-1 text-xs text-[var(--ink-soft)] leading-relaxed">
          {analysis.summary}
        </p>

        {/* 3-Column Highlights */}
        <div className="stats-detail mt-3">
          <div className="stat-detail-item">
            <span className="stat-detail-value">{uniqueTierCount} 个梯队</span>
            <span className="stat-detail-label">推荐分层架构</span>
          </div>
          <div className="stat-detail-item">
            <span className="stat-detail-value">{analysis.existingModelCount} 款</span>
            <span className="stat-detail-label">API 站当前模型</span>
          </div>
          <div className="stat-detail-item">
            <span className="stat-detail-value" style={{ color: 'oklch(0.55 0.12 155)' }}>
              {analysis.recommendations.length} 个节点
            </span>
            <span className="stat-detail-label">免费直连容灾池</span>
          </div>
        </div>

        {/* Navigation Tabs */}
        <div className="mt-4 flex flex-wrap gap-1.5 border-b border-[var(--line)] pb-2 text-xs">
          <button
            type="button"
            className={`pill !h-8 !px-3 text-xs ${activeTab === 'topology' ? 'active' : ''}`}
            onClick={() => setActiveTab('topology')}
          >
            <UiIcon name="layers" size={12} className="mr-1 inline" />
            分层拓扑方案
          </button>
          <button
            type="button"
            className={`pill !h-8 !px-3 text-xs ${activeTab === 'batch_json' ? 'active' : ''}`}
            onClick={() => setActiveTab('batch_json')}
          >
            <UiIcon name="code" size={12} className="mr-1 inline" />
            New API 批量 JSON
          </button>
          <button
            type="button"
            className={`pill !h-8 !px-3 text-xs ${activeTab === 'curl' ? 'active' : ''}`}
            onClick={() => setActiveTab('curl')}
          >
            <UiIcon name="terminal" size={12} className="mr-1 inline" />
            cURL 终端脚本
          </button>
          <button
            type="button"
            className={`pill !h-8 !px-3 text-xs ${activeTab === 'clients' ? 'active' : ''}`}
            onClick={() => setActiveTab('clients')}
          >
            <UiIcon name="monitor" size={12} className="mr-1 inline" />
            客户端直连预设
          </button>
        </div>

        {/* Tab 1: Topology Plan */}
        {activeTab === 'topology' && (
          <div className="mt-4 space-y-4 max-h-[58vh] overflow-y-auto pr-1">
            {analysis.recommendations.map((rec) => {
              const isCopied = copiedSingleId === rec.station.id;
              return (
                <div
                  key={rec.station.id}
                  className="rounded-xl border border-[var(--line)] bg-[var(--paper)] p-3.5 transition-all hover:border-[var(--ink-soft)]"
                >
                  <div className="flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between">
                    <div className="flex items-center gap-2">
                      <span className="rounded bg-black/5 px-2 py-0.5 text-[11px] font-semibold text-[var(--ink)]">
                        {rec.tierBadge}
                      </span>
                      <h4 className="font-medium text-sm text-[var(--ink)]">
                        {rec.station.name}
                      </h4>
                    </div>

                    <div className="flex items-center gap-2 text-xs">
                      <span className="font-mono text-[11px] text-[var(--ink-soft)]">
                        Priority: <strong className="text-[var(--ink)]">{rec.recommendedPriority}</strong>
                      </span>
                      <span className="font-mono text-[11px] text-[var(--ink-soft)]">
                        Weight: <strong className="text-[var(--ink)]">{rec.recommendedWeight}</strong>
                      </span>
                      <button
                        type="button"
                        onClick={() => handleCopySingle(rec)}
                        className={`inline-flex items-center gap-1 rounded-lg border px-2 py-1 text-[11px] transition-all ${
                          isCopied
                            ? 'border-emerald-500 bg-emerald-50 text-emerald-700'
                            : 'border-[var(--line)] hover:bg-[var(--paper-soft)]'
                        }`}
                        title="复制单个渠道的 New API JSON"
                      >
                        <UiIcon name={isCopied ? 'check' : 'copy'} size={11} />
                        <span>{isCopied ? '已复制' : '复制渠道JSON'}</span>
                      </button>
                    </div>
                  </div>

                  <p className="mt-1.5 text-xs text-[var(--ink-soft)] leading-normal">
                    {rec.reason}
                  </p>

                  {/* Endpoint & Models Spec */}
                  <div className="mt-2.5 flex flex-wrap items-center gap-2 text-[11px]">
                    <span className="rounded bg-[var(--paper-soft)] px-2 py-0.5 font-mono text-[var(--ink-soft)] border border-[var(--line)]">
                      Base URL: {rec.station.apiBaseUrl}
                    </span>
                    <span className="rounded bg-[var(--paper-soft)] px-2 py-0.5 font-mono text-[var(--ink-soft)] border border-[var(--line)]">
                      测活模型: {rec.testModel}
                    </span>
                  </div>

                  {/* Matched Models */}
                  {rec.matchedExistingModels.length > 0 && (
                    <div className="mt-2 flex flex-wrap items-center gap-1.5 text-[10px]">
                      <span className="text-emerald-700 font-medium">主备冗余模型:</span>
                      {rec.matchedExistingModels.map((m) => (
                        <span key={m} className="rounded bg-emerald-50 px-1.5 py-0.2 text-emerald-800 border border-emerald-200">
                          {m}
                        </span>
                      ))}
                    </div>
                  )}

                  {/* Expanded Models */}
                  {rec.expandedNewModels.length > 0 && (
                    <div className="mt-1 flex flex-wrap items-center gap-1.5 text-[10px]">
                      <span className="text-blue-700 font-medium">能力拓展模型:</span>
                      {rec.expandedNewModels.slice(0, 5).map((m) => (
                        <span key={m} className="rounded bg-blue-50 px-1.5 py-0.2 text-blue-800 border border-blue-200">
                          {m}
                        </span>
                      ))}
                    </div>
                  )}
                </div>
              );
            })}
          </div>
        )}

        {/* Tab 2: Batch JSON Export */}
        {activeTab === 'batch_json' && (
          <div className="mt-4 space-y-3">
            <div className="flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between">
              <label htmlFor="token-placeholder-input" className="text-xs text-[var(--ink-soft)]">
                统一令牌占位符（可选，默认 <code>sk-your-upstream-token-here</code>）：
              </label>
              <div className="flex items-center gap-2">
                <input
                  id="token-placeholder-input"
                  type="text"
                  placeholder="sk-..."
                  value={apiKeyPlaceholder}
                  onChange={(e) => setApiKeyPlaceholder(e.target.value)}
                  className="rounded-lg border border-[var(--line)] bg-[var(--paper)] px-2.5 py-1 font-mono text-xs text-[var(--ink)] outline-none"
                />
                <button
                  type="button"
                  onClick={handleCopyBatch}
                  className={`inline-flex items-center gap-1.5 rounded-full px-3 py-1.5 text-xs font-medium text-[var(--paper)] transition-all ${
                    copiedBatch ? 'bg-emerald-600' : 'bg-[var(--ink)] hover:opacity-90'
                  }`}
                >
                  <UiIcon name={copiedBatch ? 'check' : 'copy'} size={12} />
                  <span>{copiedBatch ? '已复制全部' : '一键复制全部渠道 JSON'}</span>
                </button>
              </div>
            </div>

            <pre className="max-h-[50vh] overflow-x-auto rounded-xl border border-[var(--line)] bg-[var(--paper-soft)] p-3.5 font-mono text-xs text-[var(--ink)] leading-relaxed select-all">
              {batchJsonString}
            </pre>
            <div className="mt-2 flex items-start gap-1.5 text-[11px] text-[var(--ink-soft)]">
              <UiIcon name="info" size={13} className="shrink-0 text-[var(--ink-soft)] mt-0.5" />
              <span>
                <strong>使用指引</strong>：在 New API 管理后台，进入「渠道管理」点击创建或通过脚本将各站点 JSON 注入，即可一键完成全套公益站渠道的最佳路由编排。
              </span>
            </div>
          </div>
        )}

        {/* Tab 3: cURL Terminal Script */}
        {activeTab === 'curl' && (
          <div className="mt-4 space-y-3">
            <div className="flex items-center justify-between">
              <span className="text-xs text-[var(--ink-soft)]">
                终端一键自动注入脚本（支持设置 <code>NEWAPI_ADMIN_TOKEN</code>）：
              </span>
              <button
                type="button"
                onClick={handleCopyCurl}
                className={`inline-flex items-center gap-1.5 rounded-full px-3 py-1.5 text-xs font-medium text-[var(--paper)] transition-all ${
                  copiedCurl ? 'bg-emerald-600' : 'bg-[var(--ink)] hover:opacity-90'
                }`}
              >
                <UiIcon name={copiedCurl ? 'check' : 'copy'} size={12} />
                <span>{copiedCurl ? '已复制脚本' : '复制终端 cURL 脚本'}</span>
              </button>
            </div>

            <pre className="max-h-[50vh] overflow-x-auto rounded-xl border border-[var(--line)] bg-[var(--paper-soft)] p-3.5 font-mono text-xs text-[var(--ink)] leading-relaxed select-all">
              {curlScript}
            </pre>
            <p className="text-[11px] text-[var(--ink-soft)]">
              在服务器或本地终端中执行 <code>NEWAPI_ADMIN_TOKEN="你的管理员Key" bash script.sh</code>，即可全自动将推荐渠道建立在您的 API 站点中。
            </p>
          </div>
        )}

        {/* Tab 4: Direct Client Guide */}
        {activeTab === 'clients' && (
          <div className="mt-4 space-y-4 max-h-[55vh] overflow-y-auto pr-1">
            <div className="rounded-xl border border-[var(--line)] bg-[var(--paper)] p-3.5">
              <h4 className="font-medium text-sm text-[var(--ink)] flex items-center gap-1.5">
                <UiIcon name="monitor" size={14} className="text-emerald-600" />
                <span>NextChat / Chatbox / Cherry Studio 接入</span>
              </h4>
              <ul className="mt-2 space-y-1.5 text-xs text-[var(--ink-soft)]">
                <li>• <strong>接口地址 (Base URL)</strong>: <code className="font-mono text-[var(--ink)]">{apiEndpoint}/v1</code></li>
                <li>• <strong>API 密钥 (API Key)</strong>: 在站点控制台「令牌」页面生成以 <code className="font-mono text-[var(--ink)]">sk-</code> 开头的密钥</li>
                <li>• <strong>推荐默认模型</strong>: <code className="font-mono text-[var(--ink)]">{analysis.recommendations.find((r) => r.tier === 'primary_ha')?.recommendedModels[0] || 'claude-sonnet-5'}</code>、<code className="font-mono text-[var(--ink)]">deepseek-v4-pro</code>、<code className="font-mono text-[var(--ink)]">gpt-5.5</code></li>
              </ul>
            </div>

            <div className="rounded-xl border border-[var(--line)] bg-[var(--paper)] p-3.5">
              <h4 className="font-medium text-sm text-[var(--ink)] flex items-center gap-1.5">
                <UiIcon name="terminal" size={14} className="text-blue-600" />
                <span>Cursor / Claude Code / Cline 开发者配置</span>
              </h4>
              <ul className="mt-2 space-y-1.5 text-xs text-[var(--ink-soft)]">
                <li>• <strong>Override OpenAI Base URL</strong>: <code className="font-mono text-[var(--ink)]">{apiEndpoint}/v1</code></li>
                <li>• <strong>Model Mapping</strong>: 针对长文本和代码审查，推荐直接输入已建立的公益站后端模型。</li>
                <li>• <strong>流式输出保护</strong>: MangoApi 已内置流终结契约与思维链剥离保护，Cursor 代码补全与 Agent 工具调用 100% 稳定交付。</li>
              </ul>
            </div>

            <div className="rounded-xl border border-[var(--line)] bg-[var(--paper)] p-3.5">
              <h4 className="font-medium text-sm text-[var(--ink)] flex items-center gap-1.5">
                <UiIcon name="shield" size={14} className="text-amber-600" />
                <span>运维安全建议</span>
              </h4>
              <p className="mt-1 text-xs text-[var(--ink-soft)] leading-normal">
                公益站节点虽免费，但可能存在单日 RPM 频率限制或偶发维护。将推荐方案中的 Priority 保持分层（10: 主力、8: 备用、5: 兜底），New API 会在检测到 429 或限流时自动以毫秒级平滑降级，确保上游永远不卡顿。
              </p>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};
